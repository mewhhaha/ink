const default_source = "/usr/share/blender/5.2/datafiles/colormanagement/luts";
const output = new URL(
  "../packages/rendering/src/agx_luts_generated.ts",
  import.meta.url,
);
const source_names = [
  ["AGX_SDR_LUT", "AgX_Base_sRGB.cube"],
  ["AGX_HDR_LUT", "AgX_Rec2100-HLG_p3_lim.cube"],
] as const;
const baked_size = 29;

if (import.meta.main) await bake_agx_luts(Deno.args);

export async function bake_agx_luts(
  arguments_: readonly string[],
): Promise<void> {
  const { check, source } = parse_arguments(arguments_);
  const declarations: string[] = [];
  for (const [name, filename] of source_names) {
    const source_path = `${source}/${filename}`;
    const cube = parse_cube(await Deno.readTextFile(source_path), source_path);
    const encoded = encode_half_float_lut(cube, source_path);
    declarations.push(
      `export const ${name}_BASE64 =\n  ${format_string(encoded)};`,
    );
  }
  const generated =
    `${"// Generated by scripts/bake_agx_luts.ts from Blender 5.2's OCIO AgX formation LUTs."}\n// https://github.com/blender/blender/tree/v5.2.0/release/datafiles/colormanagement\n// Source terms are retained in packages/rendering/AGX_LICENSE.txt.\nexport const AGX_LUT_SIZE = ${baked_size};\n\n${
      declarations.join("\n\n")
    }\n`;
  if (!check) {
    await Deno.writeTextFile(output, generated);
    console.log(`wrote ${output.pathname}`);
    return;
  }
  const current = await Deno.readTextFile(output);
  if (current !== generated) {
    throw new Error(
      `${output.pathname} does not match AgX LUTs in ${source}; run this command without --check`,
    );
  }
  console.log(`verified ${output.pathname}`);
}

function parse_arguments(arguments_: readonly string[]): {
  readonly check: boolean;
  readonly source: string;
} {
  let check = false;
  let source = default_source;
  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];
    if (argument === "--check") {
      check = true;
      continue;
    }
    if (argument === "--source" && arguments_[index + 1] !== undefined) {
      source = arguments_[index + 1];
      index += 1;
      continue;
    }
    throw new Error(
      `usage: deno run --allow-read --allow-write scripts/bake_agx_luts.ts [--source LUT_DIRECTORY] [--check], received ${
        JSON.stringify(arguments_)
      }`,
    );
  }
  return { check, source };
}

function parse_cube(source: string, source_path: string): readonly number[][] {
  const size_match = source.match(/^LUT_3D_SIZE\s+(\d+)$/m);
  if (size_match === null) {
    throw new Error(`AgX LUT ${source_path} has no LUT_3D_SIZE declaration`);
  }
  const source_size = Number(size_match[1]);
  if ((source_size - 1) % (baked_size - 1) !== 0) {
    throw new Error(
      `AgX LUT ${source_path} size ${source_size} cannot be sampled exactly at ${baked_size} points`,
    );
  }
  const rows = source.split("\n").flatMap((line) => {
    const trimmed = line.trim();
    if (
      trimmed === "" || trimmed.startsWith("#") ||
      /^[A-Z][A-Z0-9_]*\b/.test(trimmed)
    ) {
      return [];
    }
    const channels = trimmed.split(/\s+/).map(Number);
    if (
      channels.length !== 3 ||
      channels.some((channel) => !Number.isFinite(channel))
    ) {
      throw new Error(
        `AgX LUT ${source_path} contains malformed row ${JSON.stringify(line)}`,
      );
    }
    return [channels];
  });
  const expected_rows = source_size ** 3;
  if (rows.length !== expected_rows) {
    throw new Error(
      `AgX LUT ${source_path} declares ${source_size}³ but contains ${rows.length} rows; expected ${expected_rows}`,
    );
  }
  const stride = (source_size - 1) / (baked_size - 1);
  const sampled: number[][] = [];
  for (let blue = 0; blue < source_size; blue += stride) {
    for (let green = 0; green < source_size; green += stride) {
      for (let red = 0; red < source_size; red += stride) {
        sampled.push(rows[red + green * source_size + blue * source_size ** 2]);
      }
    }
  }
  return sampled;
}

function encode_half_float_lut(
  rows: readonly number[][],
  source_path: string,
): string {
  const bytes = new Uint8Array(rows.length * 8);
  const view = new DataView(bytes.buffer);
  for (let index = 0; index < rows.length; index += 1) {
    const channels = [...rows[index], 1];
    for (let channel = 0; channel < channels.length; channel += 1) {
      const value = channels[channel];
      if (value < 0 || value > 1) {
        throw new Error(
          `AgX LUT ${source_path} channel ${value} at row ${index} is outside [0, 1]`,
        );
      }
      view.setUint16((index * 4 + channel) * 2, float16(value), true);
    }
  }
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function float16(value: number): number {
  const bits = new Uint32Array(1);
  new Float32Array(bits.buffer)[0] = value;
  const source = bits[0];
  const sign = (source >>> 16) & 0x8000;
  const exponent = ((source >>> 23) & 0xff) - 127 + 15;
  const mantissa = source & 0x7fffff;
  if (exponent <= 0) {
    if (exponent < -10) return sign;
    return sign | ((mantissa | 0x800000) >>> (14 - exponent));
  }
  if (exponent >= 31) return sign | 0x7c00;
  return sign | (exponent << 10) | (mantissa >>> 13);
}

function format_string(encoded: string): string {
  const lines = encoded.match(/.{1,100}/g) ?? [];
  return lines.map((line) => JSON.stringify(line)).join(" +\n  ");
}
